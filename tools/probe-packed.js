/* probe-packed.js — for tools/electron-probe.cjs: the station geometry is
 * stored as src/ports/<id>.js.gz (tools/pack.cjs), and a built .exe ships
 * only those. Ask the running game for every port's geometry and check it
 * arrives, then fly to a station so one is actually drawn.
 *
 *     PROBE_EXE=<path to Manifest.exe> node tools/electron-probe.cjs tools/probe-packed.js
 */
const PortGeo = window.PortGeo, PortLib = window.PortLib;
const ids = Object.keys(PortLib).filter(id => PortLib[id].lazy);
const before = ids.length;
const res = { asked: before, loaded: 0, failed: [] };
/* Through the page's own path: a synchronous GET on game://, which the
 * scheme answers by unpacking the .gz (electron/packed.js). */
for (const id of ids) {
  if (PortGeo.load(id)) res.loaded++;
  else res.failed.push(id + ':' + PortGeo.state(id));
}
/* And one fetched by hand, to see the bytes the page is given. */
const r = await fetch('src/ports/' + ids[0] + '.js', { cache: 'no-store' });
const txt = await r.text();
res.sample = { id: ids[0], status: r.status, type: r.headers.get('content-type'), bytes: txt.length,
               startsLikeTheGenerator: /^\/\* .* GENERATED by tools\/glb2hulls\.js/.test(txt) };
const gz = await fetch('src/ports/' + ids[0] + '.js.gz', { cache: 'no-store' });
res.gzShipped = gz.status;
/* Fly in to the nearest port so the drawn station is in the screenshot. */
const G = window.Game, Sim = window.Sim;
G.title = null;
const port = G.sys.bodies.find(b => b.market && !b.surface && !b.underground);
if (port) { Sim.dockShip(G.ship, port, G.sys, G.t); G.viewMode = 'external'; }
await wait(1500);
await shot('packed-station');
log(JSON.stringify(res));
return (res.loaded === before && res.sample.status === 200 && res.sample.startsLikeTheGenerator ? 'PASS ' : 'FAIL ') + JSON.stringify(res);
